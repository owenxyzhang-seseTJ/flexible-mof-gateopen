#!/usr/bin/env python3
"""Make deterministic P1, fully occupied representatives of X-pcu-5-Zn.

The deposited CIF contains crystallographic disorder and symmetry.  RASPA's
rigid-framework reader is most reproducible when it receives an explicit P1
cell with one atom at every site and no fractional occupancies.  This script
keeps the major disorder component for alpha/gamma.  The beta CIF has several
0.5-occupancy sites without disorder-assembly labels; for each such label it
keeps half of the symmetry-expanded positions (a documented ordered
representative, not a new refined structure).
"""

from __future__ import annotations

import argparse
import itertools
import json
import math
import tempfile
from collections import Counter, defaultdict
from pathlib import Path

import gemmi
from pymatgen.core import Lattice


EXPECTED = {
    "alpha": Counter({"C": 64, "H": 44, "N": 4, "O": 16, "S": 8, "Zn": 4}),
    "beta": Counter({"C": 128, "H": 88, "N": 8, "O": 32, "S": 16, "Zn": 8}),
    "gamma": Counter({"C": 128, "H": 88, "N": 8, "O": 32, "S": 16, "Zn": 8}),
}


def _block_to_temp(source: Path, phase: str) -> Path:
    """Extract one data block so gemmi does not see the later reduction blocks."""
    text = source.read_text(encoding="utf-8", errors="replace")
    start = text.index(f"data_{phase}")
    next_block = text.find("\ndata_", start + 1)
    end = len(text) if next_block < 0 else next_block
    handle = tempfile.NamedTemporaryFile(prefix=f"xpcu5zn_{phase}_", suffix=".cif", delete=False)
    path = Path(handle.name)
    handle.write(text[start:end].encode("utf-8"))
    handle.close()
    return path


def _mod1(value: float) -> float:
    value = value % 1.0
    return 0.0 if abs(value - 1.0) < 1e-10 else value


def _select_sites(structure: gemmi.SmallStructure, phase: str):
    all_sites = list(structure.get_all_unit_cell_sites())
    by_label: dict[str, list] = defaultdict(list)
    for site in all_sites:
        by_label[site.label].append(site)
    lattice = Lattice.from_parameters(
        structure.cell.a,
        structure.cell.b,
        structure.cell.c,
        structure.cell.alpha,
        structure.cell.beta,
        structure.cell.gamma,
    )

    selected = []
    if phase in {"alpha", "gamma"}:
        # In both blocks the two alternatives have occupancies on opposite
        # sides of 0.5 (alpha: 0.616/0.384 and 0.638/0.362; gamma: 0.51/0.49).
        selected = [site for site in all_sites if site.occ >= 0.5]
    else:
        for label, sites in by_label.items():
            occ = sites[0].occ
            if occ >= 0.999:
                selected.extend(sites)
            else:
                # Every beta disordered label is 0.5 occupied.  Choosing a
                # deterministic half supplies the expected integer formula.
                # Some symmetry-generated alternatives are unrealistically
                # close (e.g. the two H13 positions); choose an independent
                # half rather than accepting a sub-angstrom overlap.
                keep = int(round(occ * len(sites)))
                chosen = None
                for combo in itertools.combinations(sites, keep):
                    valid = True
                    for left, right in itertools.combinations(combo, 2):
                        d, _ = lattice.get_distance_and_image(
                            [left.fract.x, left.fract.y, left.fract.z],
                            [right.fract.x, right.fract.y, right.fract.z],
                        )
                        if d < 0.70:
                            valid = False
                            break
                    if valid:
                        chosen = combo
                        break
                if chosen is None:
                    raise RuntimeError(f"could not choose a non-overlapping half for beta label {label}")
                selected.extend(chosen)

    # Wrap and de-duplicate coordinates generated by special positions.
    unique = []
    seen = set()
    for site in selected:
        coords = (_mod1(site.fract.x), _mod1(site.fract.y), _mod1(site.fract.z))
        key = (site.type_symbol, *(round(x, 8) for x in coords))
        if key in seen:
            continue
        seen.add(key)
        unique.append((site.type_symbol, coords, site.label, float(site.occ)))
    return structure, unique


def _write_p1(path: Path, phase: str, structure: gemmi.SmallStructure, selected) -> Counter:
    cell = structure.cell
    counts = Counter(element for element, *_ in selected)
    lines = [
        f"data_X_pcu_5_Zn_{phase}_ordered_P1",
        "# Ordered representative generated from CCDC 1856631/1856628/1856629 SI CIF.",
        "# Disorder alternatives were resolved deterministically; this is not a new refinement.",
        "_symmetry_space_group_name_H-M 'P 1'",
        "_symmetry_Int_Tables_number 1",
        f"_cell_length_a {cell.a:.8f}",
        f"_cell_length_b {cell.b:.8f}",
        f"_cell_length_c {cell.c:.8f}",
        f"_cell_angle_alpha {cell.alpha:.8f}",
        f"_cell_angle_beta {cell.beta:.8f}",
        f"_cell_angle_gamma {cell.gamma:.8f}",
        "loop_",
        "_symmetry_equiv_pos_as_xyz",
        "'x, y, z'",
        "",
        "loop_",
        "_atom_site_label",
        "_atom_site_type_symbol",
        "_atom_site_fract_x",
        "_atom_site_fract_y",
        "_atom_site_fract_z",
        "_atom_site_occupancy",
    ]
    for index, (element, (x, y, z), _label, _occ) in enumerate(selected, start=1):
        lines.append(f"{element}{index} {element} {x:.8f} {y:.8f} {z:.8f} 1.0")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return counts


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    audit = {"source": str(args.source), "phases": {}}
    for phase in ("alpha", "beta", "gamma"):
        temp = _block_to_temp(args.source, phase)
        try:
            structure = gemmi.read_small_structure(str(temp))
            structure, selected = _select_sites(structure, phase)
            out = args.output_dir / f"X-pcu-5-Zn_{phase}_ordered_P1.cif"
            counts = _write_p1(out, phase, structure, selected)
            expected = EXPECTED[phase]
            if counts != expected:
                raise RuntimeError(f"{phase} formula mismatch: got {counts}, expected {expected}")
            audit["phases"][phase] = {
                "output": str(out),
                "atoms": len(selected),
                "formula_counts": dict(sorted(counts.items())),
                "cell_parameters": [structure.cell.a, structure.cell.b, structure.cell.c, structure.cell.alpha, structure.cell.beta, structure.cell.gamma],
                "disorder_policy": "major_component" if phase in {"alpha", "gamma"} else "half_of_each_0.5_occupancy_label",
            }
            print(f"{phase}: atoms={len(selected)} formula={dict(counts)} -> {out}")
        finally:
            temp.unlink(missing_ok=True)
    audit_path = args.output_dir / "ordered_structure_audit.json"
    audit_path.write_text(json.dumps(audit, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {audit_path}")


if __name__ == "__main__":
    main()
